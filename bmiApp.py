import streamlit as st

# ส่วนที่ 1 หัวหน้าเรื่อง
st.markdown("# 🩺 แอปคำนวณค่า BMI")
st.write("กรุณากรอกข้อมูลเพื่อคำนวณค่าดัชนีมวลกาย (BMI)")

# ส่วนที่ 2 รับน้ำหนักและส่วนสูง
weight = st.number_input(
    "กรอกน้ำหนักของคุณ (กิโลกรัม):",
    min_value=1.0,
    step=0.1
)

height_cm = st.number_input(
    "กรอกส่วนสูงของคุณ (เซนติเมตร):",
    min_value=1.0,
    step=0.1
)

# ส่วนที่ 3 ปุ่มคำนวณ
if st.button("คำนวณ BMI 🧮"):

    # แปลงส่วนสูงจากเซนติเมตรเป็นเมตร
    height_m = height_cm / 100

    # คำนวณค่า BMI
    bmi = weight / (height_m ** 2)

    st.write("---")
    st.header(f"ค่า BMI ของคุณคือ: **{bmi:.2f}**")

    # ส่วนที่ 4 แปลผลค่า BMI
    if bmi < 18.5:
        st.warning("⚠️ คุณมีน้ำหนักต่ำกว่าเกณฑ์")

    elif 18.5 <= bmi < 23.0:
        st.success("✅ คุณมีน้ำหนักอยู่ในเกณฑ์ปกติ")

    elif 23.0 <= bmi < 25.0:
        st.info("ℹ️ คุณมีน้ำหนักเกินเกณฑ์")

    else:
        st.error("🚨 คุณอยู่ในเกณฑ์อ้วน ควรระวังเรื่องสุขภาพและออกกำลังกาย")

# ข้อมูลผู้จัดทำ
st.divider()
st.write("จัดทำโดย นางสาวภิภัทรภรณ์ สมพันธ์ เลขที่ 26 ม.4/15")
